"""Normalize the fixed V1.4 role dictionary and billing permissions.

This only removes placeholder role/permission codes generated by the old
demonstration seeder. It keeps real assignments and is safe to repeat.
"""
from db_connection import connect


ROLES = {
    "platform_admin": "平台管理员",
    "maintenance_engineer": "设备运维工程师",
    "customer_service": "客服复核员",
    "vehicle_owner": "车主",
    "fleet_admin": "车队管理员",
    "operator_manager": "运营商负责人",
}

PERMISSIONS = {
    "billing.order.read": "读取订单",
    "billing.order.create": "启动订单",
    "billing.order.finish": "结束订单",
    "billing.order.cancel": "取消订单",
    "billing.meter_reading.create": "上报电量采样",
    "billing.pricing_rule.read": "读取价格规则",
    "billing.pricing_rule.create": "创建价格规则",
    "billing.pricing_rule.disable": "停用价格规则",
    "billing.price_review.read": "读取价格审批",
    "billing.price_review.create": "提交价格审批",
    "billing.price_review.decide": "决定价格审批",
    "billing.payment.read": "读取支付记录",
    "billing.payment.create": "发起个人支付",
    "billing.refund.read": "读取退款记录",
    "billing.refund.create": "发起退款",
    "billing.order_review.create": "处理订单复核",
}

ROLE_PERMISSIONS = {
    "platform_admin": tuple(PERMISSIONS),
    "customer_service": ("billing.order.read","billing.pricing_rule.read","billing.payment.read",
                         "billing.refund.read","billing.refund.create","billing.order_review.create"),
    "vehicle_owner": ("billing.order.read","billing.order.create","billing.order.cancel",
                      "billing.pricing_rule.read","billing.payment.read","billing.payment.create",
                      "billing.refund.read"),
    "fleet_admin": ("billing.order.read","billing.order.create","billing.order.cancel",
                    "billing.pricing_rule.read","billing.payment.read","billing.refund.read"),
    "maintenance_engineer": ("billing.order.read","billing.order.finish","billing.meter_reading.create"),
    "operator_manager": ("billing.order.read","billing.pricing_rule.read","billing.refund.read"),
}


def main():
    db=connect()
    try:
        with db.cursor() as cur:
            cur.execute("DELETE ar FROM sys_account_role ar JOIN sys_role r ON r.role_id=ar.role_id "
                        "WHERE r.role_code LIKE 'sys_role-role_cod-%'")
            cur.execute("DELETE rp FROM sys_role_permission rp JOIN sys_role r ON r.role_id=rp.role_id "
                        "WHERE r.role_code LIKE 'sys_role-role_cod-%'")
            cur.execute("DELETE rp FROM sys_role_permission rp JOIN sys_permission p ON p.permission_id=rp.permission_id "
                        "WHERE p.permission_code LIKE 'sys_perm-permissi-%'")
            cur.execute("DELETE FROM sys_role WHERE role_code LIKE 'sys_role-role_cod-%'")
            cur.execute("DELETE FROM sys_permission WHERE permission_code LIKE 'sys_perm-permissi-%'")
            for code,name in ROLES.items():
                cur.execute("INSERT INTO sys_role(role_code,role_name) VALUES (%s,%s) "
                            "ON DUPLICATE KEY UPDATE role_name=VALUES(role_name)",(code,name))
            for code,name in PERMISSIONS.items():
                cur.execute("INSERT INTO sys_permission(permission_code,permission_name) VALUES (%s,%s) "
                            "ON DUPLICATE KEY UPDATE permission_name=VALUES(permission_name)",(code,name))
            cur.execute("SELECT role_id,role_code FROM sys_role")
            role_ids={r["role_code"]:r["role_id"] for r in cur.fetchall()}
            cur.execute("SELECT permission_id,permission_code FROM sys_permission")
            permission_ids={p["permission_code"]:p["permission_id"] for p in cur.fetchall()}
            for role,codes in ROLE_PERMISSIONS.items():
                for code in codes:
                    cur.execute("INSERT IGNORE INTO sys_role_permission(role_id,permission_id) VALUES (%s,%s)",
                                (role_ids[role],permission_ids[code]))
            cur.execute("INSERT IGNORE INTO sys_account_role(account_id,role_id) "
                        "SELECT account_id,%s FROM app_user WHERE account_id IS NOT NULL",(role_ids["vehicle_owner"],))
        db.commit()
    except Exception:
        db.rollback()
        raise
    finally:
        db.close()


if __name__=="__main__":
    main()
