  (`incident_id`, `action_type`, `target_type`, `target_id`, `action_at`, `actor_account_id`, `approved_by`, `reason`, `result`)
select i.`incident_id`, a.`action_type`, 'none', null,
       case a.`action_type` when 'declare' then i.`declared_at` else i.`closed_at` end,
       101, case when a.`action_type` = 'close' then 101 else null end,
       case a.`action_type` when 'declare' then '按 SLA 宣布事件' else '复盘通过后关闭事件' end,
       case a.`action_type` when 'declare' then '已宣布' else '已关闭' end
  from `incident` i
  join (select 'declare' as action_type union all select 'close') a
 where i.`incident_id` between 921 and 940;

