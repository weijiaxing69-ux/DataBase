-- -------------------------------------------------------------
-- N2 事件状态跳步：restored 不能退回 contained
-- 预期：ERROR 1644 (45000) 非法的事件状态迁移...
-- -------------------------------------------------------------
update incident set status = 'contained' where incident_id = 902;

-- -------------------------------------------------------------
-- N3 已关闭事件不能再变更状态（终态）
-- 预期：ERROR 1644 (45000) 非法的事件状态迁移...
-- 前置：13 号脚本已把 901 关闭；若未执行，请先执行 13。
-- -------------------------------------------------------------
update incident set status = 'restored' where incident_id = 901;

-- -------------------------------------------------------------
-- N4 同场站已有进行中事件时重复声明，被生成列唯一键拒绝
-- 预期：ERROR 1062 (23000) Duplicate entry '3:901:hardware' for key 'incident.uq_incident_active_key'
-- 前置：13 号脚本第 7 步已自动生成场站 901 的进行中事件。
-- -------------------------------------------------------------
set @new_incident_id = null;
call sp_declare_incident(3, 901, 'hardware', 'P2', '重复声明测试', 101, null, @new_incident_id);

-- -------------------------------------------------------------
-- N5 场站与运营商不匹配，拒绝声明
-- 预期：ERROR 1644 (45000) 场站不属于该运营商，拒绝声明事件
-- -------------------------------------------------------------
set @new_incident_id = null;
call sp_declare_incident(1, 901, 'power', 'P1', '跨运营商声明测试', 101, null, @new_incident_id);

-- -------------------------------------------------------------
-- N6 备件超量领用，被库存触发器拒绝
-- 预期：ERROR 1644 (45000) 备件库存不足，拒绝领用
-- -------------------------------------------------------------
insert into part_usage
  (usage_id, work_order_id, part_id, qty, used_at, used_by, note)
values
  (999, 905, 901, 999, utc_timestamp(3), 102, '超量领用测试');
