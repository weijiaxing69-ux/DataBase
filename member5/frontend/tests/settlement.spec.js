import { test, expect } from '@playwright/test'

async function login(page, username) {
  await page.getByLabel('账号', { exact: true }).fill(username)
  await page.getByLabel('密码', { exact: true }).fill('ChargeDemo-2026!')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page.getByRole('button', { name: '退出', exact: true })).toBeVisible()
}
async function switchUser(page, username) {
  await page.getByRole('button', { name: '退出', exact: true }).click()
  await login(page, username)
}
async function confirm(page) {
  await page.getByRole('button', { name: '提交确认', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('确认结果已记录')
}
const createForm = page => page.locator('form').filter({ has: page.getByRole('button', { name: '提交', exact: true }) })

test('real settlement, difference, adjustment, reconfirmation, blue and red invoice', async ({ page }) => {
  await page.goto('/settlement/settlements')
  await login(page, 'platform_admin_demo')
  await page.getByRole('button', { name: '生成结算单', exact: true }).click()
  await page.getByLabel('运营商编号', { exact: true }).fill('1')
  await page.getByLabel('场站编号', { exact: true }).fill('1')
  await page.getByLabel('账期', { exact: true }).first().fill('2026-11')
  await page.getByRole('button', { name: '生成', exact: true }).click()
  await expect(page.getByRole('dialog')).toContainText('4.07')
  const header = await page.getByRole('dialog').getByRole('heading', { level: 2 }).innerText()
  const id = header.match(/#(\d+)/)[1]
  await confirm(page)
  await expect(page.getByRole('button', { name: '开蓝票', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: '关闭详情', exact: true }).click()
  await switchUser(page, 'operator_manager_demo')
  await page.goto('/settlement/settlements/'+id)
  await login(page, 'operator_manager_demo') // Refresh intentionally requires login.
  await confirm(page)
  await page.getByRole('button', { name: '关闭详情', exact: true }).click()
  await switchUser(page, 'customer_service_demo')
  await page.getByRole('link', { name: '对账差异', exact: true }).click()
  await page.getByRole('button', { name: '创建差异', exact: true }).click()
  let form = createForm(page)
  await form.getByLabel('结算单编号', { exact: true }).fill(id)
  await form.getByLabel('订单编号', { exact: true }).fill(process.env.E2E_ORDER_ID)
  await form.getByRole('combobox', { name: '差异类型', exact: true }).selectOption('price')
  await form.getByLabel('金额（元）', { exact: true }).fill('0.50')
  await form.getByRole('button', { name: '提交', exact: true }).click()
  let row = page.getByRole('row').filter({ hasText: process.env.E2E_ORDER_ID }).first()
  await row.getByRole('button', { name: '提交处理结论', exact: true }).click()
  await createForm(page).getByLabel('处理结论', { exact: true }).fill('browser checked price')
  await createForm(page).getByRole('button', { name: '提交', exact: true }).click()
  for (const user of ['platform_admin_demo', 'operator_manager_demo']) {
    await switchUser(page, user)
    await page.getByRole('link', { name: '对账差异', exact: true }).click()
    row = page.getByRole('row').filter({ hasText: process.env.E2E_ORDER_ID }).first()
    await row.getByRole('button', { name: '确认差异', exact: true }).click()
    await createForm(page).getByRole('button', { name: '提交', exact: true }).click()
    await expect(page.getByRole('status')).toContainText('操作成功')
  }
  await switchUser(page, 'customer_service_demo')
  await page.getByRole('link', { name: '对账差异', exact: true }).click()
  row = page.getByRole('row').filter({ hasText: process.env.E2E_ORDER_ID }).first()
  await row.getByRole('button', { name: '申请调整', exact: true }).click()
  await createForm(page).getByLabel('金额（元）', { exact: true }).fill('0.50')
  await createForm(page).getByLabel('调整原因', { exact: true }).fill('browser adjustment')
  await createForm(page).getByRole('button', { name: '提交', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('调整申请')
  await switchUser(page, 'platform_admin_demo')
  await page.getByRole('link', { name: '结算调整', exact: true }).click()
  await page.getByRole('row').filter({ hasText: 'browser adjustment' })
    .getByRole('button', { name: '审批调整', exact: true }).click()
  await createForm(page).getByLabel('审批依据', { exact: true }).fill('browser evidence reviewed')
  await createForm(page).getByRole('button', { name: '提交', exact: true }).click()
  await expect(page.getByRole('row').filter({ hasText: 'browser adjustment' })).toContainText('已批准')
  for (const user of ['platform_admin_demo', 'operator_manager_demo']) {
    await page.goto('/settlement/settlements/'+id)
    await login(page, user)
    await expect(page.getByRole('dialog')).toContainText('版本 2')
    await confirm(page)
  }
  await page.goto('/settlement/settlements/'+id)
  await login(page, 'platform_admin_demo')
  await page.getByLabel('税号', { exact: true }).fill('DEMO')
  await page.getByLabel('金额（元）', { exact: true }).fill('4.57')
  await page.getByRole('button', { name: '开蓝票', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('蓝票已开具')
  await page.getByRole('button', { name: '红冲', exact: true }).click()
  await page.getByLabel(/红冲金额/).fill('4.58')
  await page.getByLabel('原因', { exact: true }).fill('browser red')
  await page.getByRole('button', { name: '确认红冲', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('红冲金额超过')
  await page.getByLabel(/红冲金额/).fill('1.57')
  await page.getByRole('button', { name: '确认红冲', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('红票已开具')
  await page.getByRole('button', { name: '关闭详情', exact: true }).click()
  await expect(page.getByRole('row').filter({ hasText: '#'+id })).toContainText('¥3.00')
})

test('owner application and customer invoice processing retains reason', async ({ page }) => {
  await page.goto('/settlement/user-invoices')
  await login(page, 'owner_01')
  await page.getByRole('button', { name: '申请消费发票', exact: true }).click()
  await createForm(page).getByLabel('发票抬头', { exact: true }).fill('browser owner')
  await createForm(page).getByLabel('订单编号', { exact: true }).fill(process.env.E2E_ORDER_ID)
  await createForm(page).getByLabel('分配金额', { exact: true }).fill('6.00')
  await createForm(page).getByRole('button', { name: '提交', exact: true }).click()
  await expect(page.getByRole('row').filter({ hasText: 'browser owner' })).toContainText('待办理')
  await expect(page.getByRole('button', { name: '办理申请', exact: true })).toHaveCount(0)
  await switchUser(page, 'customer_service_demo')
  await page.getByRole('row').filter({ hasText: 'browser owner' })
    .getByRole('button', { name: '办理申请', exact: true }).click()
  await createForm(page).getByLabel('办理说明', { exact: true }).fill('browser invoice checked')
  await createForm(page).getByRole('button', { name: '提交', exact: true }).click()
  const row = page.getByRole('row').filter({ hasText: 'browser owner' }).filter({ hasText: '蓝票' })
  await expect(row).toContainText('已开具')
  await row.getByRole('button', { name: '查看', exact: true }).click()
  await expect(page.getByText('说明：browser invoice checked')).toBeVisible()
})

test('fleet partial receipt, duplicate trade, overpayment and fleet read-only UI', async ({ page }) => {
  await page.goto('/settlement/fleet-bills')
  await login(page, 'customer_service_demo')
  await page.getByRole('button', { name: '生成月结单', exact: true }).click()
  await createForm(page).getByLabel('车队编号', { exact: true }).fill('1')
  await createForm(page).getByLabel('账期', { exact: true }).fill('2026-11')
  await createForm(page).getByRole('button', { name: '提交', exact: true }).click()
  const row = page.getByRole('row').filter({ hasText: '2026-11-01' })
  async function pay(number, amount) {
    await row.getByRole('button', { name: '登记收款', exact: true }).click()
    await createForm(page).getByLabel('外部流水号', { exact: true }).fill(number)
    await createForm(page).getByLabel('金额（元）', { exact: true }).fill(amount)
    await createForm(page).getByRole('button', { name: '提交', exact: true }).click()
  }
  await pay('browser-cash-1', '4.00')
  await expect(row).toContainText('部分收款')
  await pay('browser-cash-1', '4.00')
  await expect(row.getByRole('cell', { name: '4.00', exact: true })).toBeVisible()
  await pay('browser-cash-2', '6.01')
  await expect(page.getByRole('alert')).toContainText('金额超过')
  await createForm(page).getByLabel('金额（元）', { exact: true }).fill('6.00')
  await createForm(page).getByRole('button', { name: '提交', exact: true }).click()
  await expect(row).toContainText('已结清')
  await switchUser(page, 'fleet_admin_demo')
  await expect(page.getByRole('button', { name: '登记收款', exact: true })).toHaveCount(0)
  await expect(page.getByRole('row').filter({ hasText: '2026-11-01' })).toContainText('已结清')
})
